BEGIN;

CREATE SCHEMA IF NOT EXISTS dw;

-- Dimensao calendario. A chave 0 representa data nao informada.
CREATE TABLE IF NOT EXISTS dw.dim_tempo (
    tempo_sk       INTEGER PRIMARY KEY,
    data_completa  DATE UNIQUE,
    dia            SMALLINT,
    mes            SMALLINT,
    nome_mes       VARCHAR(20),
    trimestre      SMALLINT,
    ano            SMALLINT,

    CONSTRAINT ck_dim_tempo_dia
        CHECK (dia IS NULL OR dia BETWEEN 1 AND 31),
    CONSTRAINT ck_dim_tempo_mes
        CHECK (mes IS NULL OR mes BETWEEN 1 AND 12),
    CONSTRAINT ck_dim_tempo_trimestre
        CHECK (trimestre IS NULL OR trimestre BETWEEN 1 AND 4),
    CONSTRAINT ck_dim_tempo_chave
        CHECK (
            (tempo_sk = 0 AND data_completa IS NULL)
            OR
            (
                tempo_sk <> 0
                AND data_completa IS NOT NULL
                AND tempo_sk = TO_CHAR(data_completa, 'YYYYMMDD')::INTEGER
            )
        )
);

COMMENT ON TABLE dw.dim_tempo IS
    'Dimensao calendario utilizada pela data do embargo.';


-- Municipio e UF formam a chave natural da localidade.
CREATE TABLE IF NOT EXISTS dw.dim_localidade (
    localidade_sk  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    municipio      VARCHAR(150) NOT NULL,
    uf             VARCHAR(20) NOT NULL,

    CONSTRAINT uq_dim_localidade
        UNIQUE (municipio, uf),
    CONSTRAINT ck_dim_localidade_uf
        CHECK (uf = 'NAO_INFORMADA' OR uf ~ '^[A-Z]{2}$')
);

COMMENT ON TABLE dw.dim_localidade IS
    'Dimensao geografica no nivel de municipio e unidade federativa.';


-- O codigo CNUC identifica a unidade de conservacao na fonte.
CREATE TABLE IF NOT EXISTS dw.dim_unidade_conservacao (
    unidade_sk     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_cnuc    VARCHAR(30) NOT NULL,
    nome_unidade   VARCHAR(200) NOT NULL,

    CONSTRAINT uq_dim_unidade_conservacao_cnuc
        UNIQUE (codigo_cnuc)
);

COMMENT ON TABLE dw.dim_unidade_conservacao IS
    'Dimensao das unidades de conservacao identificadas pelo codigo CNUC.';


-- Uma linha por combinacao de tipo de infracao e enquadramento legal.
CREATE TABLE IF NOT EXISTS dw.dim_infracao (
    infracao_sk    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_infracao  VARCHAR(200) NOT NULL,
    artigo_1       VARCHAR(30) NOT NULL DEFAULT 'NAO_INFORMADO',
    artigo_2       VARCHAR(30) NOT NULL DEFAULT 'NAO_INFORMADO',

    CONSTRAINT uq_dim_infracao
        UNIQUE (tipo_infracao, artigo_1, artigo_2)
);

COMMENT ON TABLE dw.dim_infracao IS
    'Dimensao de classificacao e enquadramento legal da infracao.';


-- Na fonte, as combinacoes esperadas sao Eletronico/NAO_SE_APLICA,
-- Papel/A e Papel/B.
CREATE TABLE IF NOT EXISTS dw.dim_origem (
    origem_sk      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem         VARCHAR(30) NOT NULL,
    serie          VARCHAR(30) NOT NULL DEFAULT 'NAO_SE_APLICA',

    CONSTRAINT uq_dim_origem
        UNIQUE (origem, serie)
);

COMMENT ON TABLE dw.dim_origem IS
    'Dimensao da origem do registro e da serie do documento.';


-- Grao: uma linha para cada registro unico de embargo (vw_num_emb)
-- publicado pelo ICMBio.
CREATE TABLE IF NOT EXISTS dw.fato_embargo (
    embargo_sk             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    embargo_id_fonte       BIGINT NOT NULL,

    -- Dimensoes degeneradas: identificadores transacionais mantidos na fato.
    numero_embargo         VARCHAR(255) NOT NULL,
    numero_auto_infracao   VARCHAR(255),
    numero_processo        VARCHAR(255),

    tempo_sk               INTEGER NOT NULL,
    localidade_sk          BIGINT NOT NULL,
    unidade_sk             BIGINT NOT NULL,
    infracao_sk            BIGINT NOT NULL,
    origem_sk              BIGINT NOT NULL,

    quantidade_embargo     SMALLINT NOT NULL DEFAULT 1,
    area_original          VARCHAR(255),
    area_ha                NUMERIC(18, 4),
    area_valida            BOOLEAN NOT NULL DEFAULT FALSE,
    hash_registro          CHAR(64) NOT NULL,
    presente_na_fonte      BOOLEAN NOT NULL DEFAULT TRUE,
    primeira_carga_id      UUID NOT NULL,
    ultima_carga_id        UUID NOT NULL,
    data_carga             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_fato_embargo_id_fonte
        UNIQUE (embargo_id_fonte),
    CONSTRAINT ck_fato_embargo_quantidade
        CHECK (quantidade_embargo = 1),
    CONSTRAINT ck_fato_embargo_area_nao_negativa
        CHECK (area_ha IS NULL OR area_ha >= 0),
    CONSTRAINT ck_fato_embargo_area_consistente
        CHECK (
            (area_valida = TRUE AND area_ha IS NOT NULL)
            OR
            (area_valida = FALSE AND area_ha IS NULL)
        ),
    CONSTRAINT ck_fato_embargo_hash
        CHECK (hash_registro ~ '^[0-9a-f]{64}$'),

    CONSTRAINT fk_fato_embargo_tempo
        FOREIGN KEY (tempo_sk)
        REFERENCES dw.dim_tempo (tempo_sk)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_fato_embargo_localidade
        FOREIGN KEY (localidade_sk)
        REFERENCES dw.dim_localidade (localidade_sk)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_fato_embargo_unidade
        FOREIGN KEY (unidade_sk)
        REFERENCES dw.dim_unidade_conservacao (unidade_sk)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_fato_embargo_infracao
        FOREIGN KEY (infracao_sk)
        REFERENCES dw.dim_infracao (infracao_sk)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_fato_embargo_origem
        FOREIGN KEY (origem_sk)
        REFERENCES dw.dim_origem (origem_sk)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_fato_embargo_primeira_carga
        FOREIGN KEY (primeira_carga_id)
        REFERENCES controle.carga (id_carga)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_fato_embargo_ultima_carga
        FOREIGN KEY (ultima_carga_id)
        REFERENCES controle.carga (id_carga)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

COMMENT ON TABLE dw.fato_embargo IS
    'Tabela fato com uma linha por embargo publicado pelo ICMBio.';
COMMENT ON COLUMN dw.fato_embargo.embargo_id_fonte IS
    'Identificador vw_num_emb, unico na fonte analisada.';
COMMENT ON COLUMN dw.fato_embargo.area_original IS
    'Texto da area conforme publicado pelo ICMBio.';
COMMENT ON COLUMN dw.fato_embargo.area_ha IS
    'Area convertida para hectares somente quando a unidade e o valor forem confiaveis.';


-- PostgreSQL nao cria indices automaticamente para as colunas que referenciam
-- chaves estrangeiras. Estes indices ajudam os joins do Power BI.
CREATE INDEX IF NOT EXISTS idx_fato_embargo_tempo
    ON dw.fato_embargo (tempo_sk);
CREATE INDEX IF NOT EXISTS idx_fato_embargo_localidade
    ON dw.fato_embargo (localidade_sk);
CREATE INDEX IF NOT EXISTS idx_fato_embargo_unidade
    ON dw.fato_embargo (unidade_sk);
CREATE INDEX IF NOT EXISTS idx_fato_embargo_infracao
    ON dw.fato_embargo (infracao_sk);
CREATE INDEX IF NOT EXISTS idx_fato_embargo_origem
    ON dw.fato_embargo (origem_sk);
CREATE INDEX IF NOT EXISTS idx_fato_embargo_presente
    ON dw.fato_embargo (presente_na_fonte);


-- Membros desconhecidos preservam registros da fato quando algum atributo
-- estiver ausente na fonte, sem quebrar as chaves estrangeiras.
INSERT INTO dw.dim_tempo (
    tempo_sk,
    data_completa,
    dia,
    mes,
    nome_mes,
    trimestre,
    ano
)
VALUES (0, NULL, NULL, NULL, 'Nao informado', NULL, NULL)
ON CONFLICT (tempo_sk) DO NOTHING;

INSERT INTO dw.dim_localidade (
    localidade_sk,
    municipio,
    uf
)
VALUES (0, 'Nao informado', 'NAO_INFORMADA')
ON CONFLICT (localidade_sk) DO NOTHING;

INSERT INTO dw.dim_unidade_conservacao (
    unidade_sk,
    codigo_cnuc,
    nome_unidade
)
VALUES (0, 'NAO_INFORMADO', 'Nao informada')
ON CONFLICT (unidade_sk) DO NOTHING;

INSERT INTO dw.dim_infracao (
    infracao_sk,
    tipo_infracao,
    artigo_1,
    artigo_2
)
VALUES (0, 'Nao informada', 'NAO_INFORMADO', 'NAO_INFORMADO')
ON CONFLICT (infracao_sk) DO NOTHING;

INSERT INTO dw.dim_origem (
    origem_sk,
    origem,
    serie
)
VALUES (0, 'Nao informada', 'NAO_SE_APLICA')
ON CONFLICT (origem_sk) DO NOTHING;

COMMIT;