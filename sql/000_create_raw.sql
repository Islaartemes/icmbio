BEGIN;

CREATE SCHEMA IF NOT EXISTS controle;
CREATE SCHEMA IF NOT EXISTS raw;

-- Uma linha por execucao do pipeline, inclusive quando o arquivo nao mudou ou
-- quando a execucao terminou com erro.
CREATE TABLE IF NOT EXISTS controle.carga (
    id_carga           UUID PRIMARY KEY,
    data_inicio        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_fim           TIMESTAMPTZ,
    arquivo_origem     TEXT NOT NULL,
    hash_sha256        CHAR(64) NOT NULL,
    status             VARCHAR(30) NOT NULL DEFAULT 'INICIADA',
    linhas_raw         INTEGER,
    linhas_stg         INTEGER,
    linhas_fato        INTEGER,
    registros_novos    INTEGER,
    registros_alterados INTEGER,
    registros_ausentes INTEGER,
    mensagem_erro      TEXT,

    CONSTRAINT ck_controle_carga_hash
        CHECK (hash_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_controle_carga_status
        CHECK (
            status IN (
                'INICIADA',
                'SEM_ALTERACAO',
                'RAW_CARREGADA',
                'STG_CARREGADA',
                'CONCLUIDA',
                'ERRO'
            )
        ),
    CONSTRAINT ck_controle_carga_contagens
        CHECK (
            COALESCE(linhas_raw, 0) >= 0
            AND COALESCE(linhas_stg, 0) >= 0
            AND COALESCE(linhas_fato, 0) >= 0
            AND COALESCE(registros_novos, 0) >= 0
            AND COALESCE(registros_alterados, 0) >= 0
            AND COALESCE(registros_ausentes, 0) >= 0
        ),
    CONSTRAINT ck_controle_carga_periodo
        CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);

COMMENT ON TABLE controle.carga IS
    'Controle operacional das execucoes do pipeline semanal do ICMBio.';

CREATE INDEX IF NOT EXISTS idx_controle_carga_hash
    ON controle.carga (hash_sha256);

CREATE INDEX IF NOT EXISTS idx_controle_carga_inicio
    ON controle.carga (data_inicio DESC);

-- Camada de entrada: preserva os atributos do ICMBio como texto para que
-- valores inesperados nao interrompam a ingestao. As conversoes de tipo e as
-- regras de negocio acontecem somente na passagem de raw para dw.
CREATE TABLE IF NOT EXISTS raw.embargo_icmbio (
    raw_sk          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Metadados tecnicos preenchidos pelo processo de extracao.
    id_carga        UUID NOT NULL,
    data_carga      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    arquivo_origem  TEXT NOT NULL,
    linha_origem    INTEGER NOT NULL,

    -- Atributos da fonte oficial.
    vw_num_emb      TEXT,
    numero_emb      TEXT,
    serie           TEXT,
    origem          TEXT,
    numero_ai       TEXT,
    cpf_cnpj        TEXT,
    autuado         TEXT,
    desc_infra      TEXT,
    desc_sanc       TEXT,
    artigo_1        TEXT,
    artigo_2        TEXT,
    tipo_infra      TEXT,
    nome_uc         TEXT,
    cnuc            TEXT,
    municipio       TEXT,
    uf              TEXT,
    data            TEXT,
    ano             TEXT,
    obs             TEXT,
    julgamento      TEXT,
    area            TEXT,
    processo        TEXT,

    CONSTRAINT uq_raw_embargo_linha_carga
        UNIQUE (id_carga, linha_origem),
    CONSTRAINT ck_raw_embargo_linha_positiva
        CHECK (linha_origem > 0),
    CONSTRAINT fk_raw_embargo_carga
        FOREIGN KEY (id_carga)
        REFERENCES controle.carga (id_carga)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

COMMENT ON TABLE raw.embargo_icmbio IS
    'Dados de areas embargadas conforme recebidos do ICMBio, antes das transformacoes.';
COMMENT ON COLUMN raw.embargo_icmbio.id_carga IS
    'UUID gerado pelo processo Python e compartilhado por todas as linhas da mesma execucao.';
COMMENT ON COLUMN raw.embargo_icmbio.linha_origem IS
    'Numero da linha no conjunto de dados de origem, usado para rastreabilidade.';
COMMENT ON COLUMN raw.embargo_icmbio.cpf_cnpj IS
    'Dado pessoal restrito a camada raw; nao deve ser enviado ao DW, Power BI ou GitHub.';
COMMENT ON COLUMN raw.embargo_icmbio.autuado IS
    'Dado pessoal restrito a camada raw; nao deve ser enviado ao DW, Power BI ou GitHub.';

CREATE INDEX IF NOT EXISTS idx_raw_embargo_id_carga
    ON raw.embargo_icmbio (id_carga);

CREATE INDEX IF NOT EXISTS idx_raw_embargo_carga_id_fonte
    ON raw.embargo_icmbio (id_carga, vw_num_emb);

COMMIT;