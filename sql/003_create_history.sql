BEGIN;

-- Historico por versao. Uma nova linha e criada somente quando o embargo e
-- novo, reaparece ou tem algum atributo relevante alterado.
CREATE TABLE IF NOT EXISTS dw.fato_embargo_historico (
    historico_sk           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    embargo_id_fonte       BIGINT NOT NULL,

    numero_embargo         VARCHAR(255) NOT NULL,
    numero_auto_infracao   VARCHAR(255),
    numero_processo        VARCHAR(255),

    tempo_sk               INTEGER NOT NULL,
    localidade_sk          BIGINT NOT NULL,
    unidade_sk             BIGINT NOT NULL,
    infracao_sk            BIGINT NOT NULL,
    origem_sk              BIGINT NOT NULL,

    quantidade_embargo     SMALLINT NOT NULL DEFAULT 1,
    area_original          VARCHAR(255),
    area_ha                NUMERIC(18, 4),
    area_valida            BOOLEAN NOT NULL DEFAULT FALSE,
    hash_registro          CHAR(64) NOT NULL,

    inicio_vigencia        TIMESTAMPTZ NOT NULL,
    fim_vigencia           TIMESTAMPTZ,
    registro_atual         BOOLEAN NOT NULL DEFAULT TRUE,
    motivo_encerramento    VARCHAR(30),
    carga_inicial_id       UUID NOT NULL,
    carga_final_id         UUID,

    CONSTRAINT ck_hist_embargo_quantidade
        CHECK (quantidade_embargo = 1),
    CONSTRAINT ck_hist_embargo_area_nao_negativa
        CHECK (area_ha IS NULL OR area_ha >= 0),
    CONSTRAINT ck_hist_embargo_area_consistente
        CHECK (
            (area_valida = TRUE AND area_ha IS NOT NULL)
            OR
            (area_valida = FALSE AND area_ha IS NULL)
        ),
    CONSTRAINT ck_hist_embargo_hash
        CHECK (hash_registro ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_hist_embargo_vigencia
        CHECK (fim_vigencia IS NULL OR fim_vigencia >= inicio_vigencia),
    CONSTRAINT ck_hist_embargo_estado
        CHECK (
            (
                registro_atual = TRUE
                AND fim_vigencia IS NULL
                AND motivo_encerramento IS NULL
                AND carga_final_id IS NULL
            )
            OR
            (
                registro_atual = FALSE
                AND fim_vigencia IS NOT NULL
                AND motivo_encerramento IN ('ALTERADO', 'AUSENTE_NA_FONTE')
                AND carga_final_id IS NOT NULL
            )
        ),

    CONSTRAINT fk_hist_embargo_tempo
        FOREIGN KEY (tempo_sk)
        REFERENCES dw.dim_tempo (tempo_sk)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_hist_embargo_localidade
        FOREIGN KEY (localidade_sk)
        REFERENCES dw.dim_localidade (localidade_sk)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_hist_embargo_unidade
        FOREIGN KEY (unidade_sk)
        REFERENCES dw.dim_unidade_conservacao (unidade_sk)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_hist_embargo_infracao
        FOREIGN KEY (infracao_sk)
        REFERENCES dw.dim_infracao (infracao_sk)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_hist_embargo_origem
        FOREIGN KEY (origem_sk)
        REFERENCES dw.dim_origem (origem_sk)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_hist_embargo_carga_inicial
        FOREIGN KEY (carga_inicial_id)
        REFERENCES controle.carga (id_carga)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_hist_embargo_carga_final
        FOREIGN KEY (carga_final_id)
        REFERENCES controle.carga (id_carga)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

COMMENT ON TABLE dw.fato_embargo_historico IS
    'Versoes historicas dos embargos, registradas somente quando houver mudanca de estado.';

-- Garante no maximo uma versao historica aberta para cada embargo.
CREATE UNIQUE INDEX IF NOT EXISTS uq_hist_embargo_versao_atual
    ON dw.fato_embargo_historico (embargo_id_fonte)
    WHERE registro_atual = TRUE;

CREATE INDEX IF NOT EXISTS idx_hist_embargo_periodo
    ON dw.fato_embargo_historico (inicio_vigencia, fim_vigencia);

CREATE INDEX IF NOT EXISTS idx_hist_embargo_carga_inicial
    ON dw.fato_embargo_historico (carga_inicial_id);

-- Fonte recomendada para as paginas de estado atual no Power BI.
CREATE OR REPLACE VIEW dw.vw_embargo_atual AS
SELECT
    f.*
FROM dw.fato_embargo AS f
WHERE f.presente_na_fonte = TRUE;

COMMENT ON VIEW dw.vw_embargo_atual IS
    'Embargos encontrados na publicacao mais recente processada com sucesso.';

COMMIT;